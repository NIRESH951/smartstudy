package com.smartstudy.planner;

import java.math.BigDecimal;
import java.time.Duration;
import java.time.Instant;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import com.smartstudy.common.BaseEntity;
import com.smartstudy.subject.Subject;
import com.smartstudy.topic.Topic;
import org.hibernate.annotations.OnDelete;
import org.hibernate.annotations.OnDeleteAction;

/** One scheduled block of study time (generated by the planner or created manually). */
@Entity
@Table(name = "study_sessions")
public class StudySession extends BaseEntity {

    @Column(name = "user_id", nullable = false)
    private Long userId;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "plan_id")
    @OnDelete(action = OnDeleteAction.SET_NULL)
    private StudyPlan plan;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "subject_id", nullable = false)
    @OnDelete(action = OnDeleteAction.CASCADE)
    private Subject subject;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "topic_id")
    @OnDelete(action = OnDeleteAction.CASCADE)
    private Topic topic;

    @Enumerated(EnumType.STRING)
    @Column(name = "session_type", nullable = false, length = 20)
    private SessionType sessionType = SessionType.STUDY;

    @Enumerated(EnumType.STRING)
    @Column(name = "source", nullable = false, length = 20)
    private SessionSource source = SessionSource.GENERATED;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    private SessionStatus status = SessionStatus.PLANNED;

    @Column(name = "start_at", nullable = false)
    private Instant startAt;

    @Column(name = "end_at", nullable = false)
    private Instant endAt;

    @Column(name = "planned_minutes", nullable = false)
    private int plannedMinutes;

    @Column(name = "actual_minutes")
    private Integer actualMinutes;

    @Column(name = "started_at")
    private Instant startedAt;

    @Column(name = "completed_at")
    private Instant completedAt;

    /** Locked sessions are never moved or deleted when the timetable is regenerated. */
    @Column(name = "locked", nullable = false)
    private boolean locked;

    @Column(name = "priority_score", precision = 5, scale = 2)
    private BigDecimal priorityScore;

    /** Human-readable explanation of why the planner chose this topic. */
    @Column(name = "reason", length = 500)
    private String reason;

    @Column(name = "notes", length = 1000)
    private String notes;

    /** The missed or incomplete session whose work this session takes over. */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "rescheduled_from_id")
    @OnDelete(action = OnDeleteAction.SET_NULL)
    private StudySession rescheduledFrom;

    protected StudySession() {
    }

    public StudySession(Long userId, Subject subject, Topic topic, SessionType sessionType, SessionSource source,
                        Instant startAt, Instant endAt) {
        this.userId = userId;
        this.subject = subject;
        this.topic = topic;
        this.sessionType = sessionType;
        this.source = source;
        this.startAt = startAt;
        this.endAt = endAt;
        this.plannedMinutes = (int) Duration.between(startAt, endAt).toMinutes();
    }

    /** Sets the time range and keeps planned minutes in sync. */
    public void setTimes(Instant startAt, Instant endAt) {
        this.startAt = startAt;
        this.endAt = endAt;
        this.plannedMinutes = (int) Duration.between(startAt, endAt).toMinutes();
    }

    public Long getUserId() {
        return userId;
    }

    public StudyPlan getPlan() {
        return plan;
    }

    public void setPlan(StudyPlan plan) {
        this.plan = plan;
    }

    public Subject getSubject() {
        return subject;
    }

    public void setSubject(Subject subject) {
        this.subject = subject;
    }

    public Topic getTopic() {
        return topic;
    }

    public void setTopic(Topic topic) {
        this.topic = topic;
    }

    public SessionType getSessionType() {
        return sessionType;
    }

    public void setSessionType(SessionType sessionType) {
        this.sessionType = sessionType;
    }

    public SessionSource getSource() {
        return source;
    }

    public SessionStatus getStatus() {
        return status;
    }

    public void setStatus(SessionStatus status) {
        this.status = status;
    }

    public Instant getStartAt() {
        return startAt;
    }

    public Instant getEndAt() {
        return endAt;
    }

    public int getPlannedMinutes() {
        return plannedMinutes;
    }

    public Integer getActualMinutes() {
        return actualMinutes;
    }

    public void setActualMinutes(Integer actualMinutes) {
        this.actualMinutes = actualMinutes;
    }

    public Instant getStartedAt() {
        return startedAt;
    }

    public void setStartedAt(Instant startedAt) {
        this.startedAt = startedAt;
    }

    public Instant getCompletedAt() {
        return completedAt;
    }

    public void setCompletedAt(Instant completedAt) {
        this.completedAt = completedAt;
    }

    public boolean isLocked() {
        return locked;
    }

    public void setLocked(boolean locked) {
        this.locked = locked;
    }

    public BigDecimal getPriorityScore() {
        return priorityScore;
    }

    public void setPriorityScore(BigDecimal priorityScore) {
        this.priorityScore = priorityScore;
    }

    public String getReason() {
        return reason;
    }

    public void setReason(String reason) {
        this.reason = reason;
    }

    public String getNotes() {
        return notes;
    }

    public void setNotes(String notes) {
        this.notes = notes;
    }

    public StudySession getRescheduledFrom() {
        return rescheduledFrom;
    }

    public void setRescheduledFrom(StudySession rescheduledFrom) {
        this.rescheduledFrom = rescheduledFrom;
    }
}
